def send_mail(sender, app_password,receiver,subject,body,LogFileName):
    
    msg = EmailMessage()
    
    msg ["From"] = sender
    msg ["To"] = receiver
    msg ["subject"] = subject
    
    msg.set_content(body)
    
    with open(LogFileName, "rb") as fobj:

        FileData = fobj.read()

        msg.add_attachment(FileData, maintype="application",subtype="octet-stream",filename=os.path.basename(LogFileName))

    smtp = smtplib.SMTP_SSL("smtp.gmail.com",465)
    
    smtp.login(sender,app_password)
    
    smtp.send_message(msg)
    
    smtp.quit()
    
def ProcessScan():
    listprocess =[]
    
    for proc in psutil.process_iter():
        info = proc.as_dict(attrs=["pid","name","username","status"])
        info["cpu_percent"] = proc.cpu_percent(None)
        info["memory_percent"] = proc.memory_percent()
        
        listprocess.append(info)
    
    return listprocess

